# Runs every game/tests/*_test.gd headless in the double-precision Godot editor build and logs time and exit code per
# script to build/godot_tests.log. Exit code 1 when any script fails, 0 otherwise.
#   -Gpu     also run the scripts in $needsGpuOrModels (they need a GPU window or the generated models in data/models)
#   -Only    run only these scripts (names with or without .gd, e.g. -Only clock_hold_test,ui_rate_test)
#   -TimeoutSec  per-script time limit (default 300)
# Needs the built GDExtension (tools/build.ps1) for scripts that use the simulation.
param(
    [switch]$Gpu,
    [string[]]$Only = @(),
    [int]$TimeoutSec = 300
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$godot = Join-Path $root 'external/godot/bin/godot.windows.editor.double.x86_64.console.exe'
$log = Join-Path $root 'build/godot_tests.log'

# Skipped unless -Gpu: need a GPU / window, or data/models generated by tools/structures (not in a fresh checkout).
$needsGpuOrModels = @(
    'docking_mechanism_test',  # generated Dragon models
    'tower_view_test',         # data/models/starbase_olp2
    'vehicle_view_test'        # Starship / Super Heavy detail models
)

$scripts = Get-ChildItem (Join-Path $root 'game/tests') -Filter '*_test.gd' | Sort-Object Name
if ($Only.Count -gt 0) {
    $names = $Only | ForEach-Object { $_ -split "," } | ForEach-Object { $_ -replace '\.gd$', '' }
    $scripts = $scripts | Where-Object { $names -contains $_.BaseName }
}

New-Item -ItemType Directory -Force (Split-Path $log) | Out-Null
"Godot tests $(Get-Date -Format s)" | Set-Content $log -Encoding utf8

$failed = @()
foreach ($s in $scripts) {
    $name = $s.BaseName
    if (-not $Gpu -and $needsGpuOrModels -contains $name) {
        "SKIP  $name (needs GPU or generated models; use -Gpu)" | ForEach-Object { Write-Host $_; Add-Content $log $_ -Encoding utf8 }
        continue
    }
    $out = Join-Path ([IO.Path]::GetTempPath()) "godot_test_$name.txt"
    $sw = [Diagnostics.Stopwatch]::StartNew()
    $p = Start-Process $godot -ArgumentList @('--headless', '--path', (Join-Path $root 'game'), '--script', "res://tests/$($s.Name)") `
        -NoNewWindow -PassThru -RedirectStandardOutput $out -RedirectStandardError "$out.err"
    $null = $p.Handle  # keeps the process handle so ExitCode is readable after WaitForExit(ms)
    if (-not $p.WaitForExit($TimeoutSec * 1000)) {
        $p.Kill()
        $code = 'TIMEOUT'
    } else {
        $code = $p.ExitCode
    }
    $sw.Stop()
    $ok = ($code -eq 0)
    $line = '{0,-5} {1}  exit={2}  {3:N1} s' -f $(if ($ok) { 'PASS' } else { 'FAIL' }), $name, $code, $sw.Elapsed.TotalSeconds
    $line | ForEach-Object { Write-Host $_; Add-Content $log $_ -Encoding utf8 }
    if (-not $ok) {
        $failed += $name
        "---- tail of $name" | Add-Content $log -Encoding utf8
        Get-Content $out -Tail 15 | Add-Content $log -Encoding utf8
        Get-Content "$out.err" -Tail 5 | Add-Content $log -Encoding utf8
    }
    Remove-Item $out, "$out.err" -ErrorAction SilentlyContinue
}

if ($failed.Count -gt 0) {
    "FAILED: $($failed -join ', ')" | ForEach-Object { Write-Host $_; Add-Content $log $_ -Encoding utf8 }
    exit 1
}
"All run scripts passed." | ForEach-Object { Write-Host $_; Add-Content $log $_ -Encoding utf8 }
exit 0
