"""Offline fit of the glare spread kernel (look fixes T13): CIE 146:2002 general disability glare function as a sum of
Gaussians, written into game/world/glare_spread_kernel.gd (generated; do not edit by hand).

    L_veil / E_gl = f(theta) = 10/theta^3 + (5/theta^2 + 0.1 p/theta)(1 + (A/62.5)^4) + 0.0025 p     [1/sr]
    [S: CIE 146:2002 "CIE equations for disability glare", general disability glare equation; theta in degrees,
     valid 0.1 .. 100 deg; A the observer's age in years, p the eye pigmentation (0.5 = average)]

The pyramid of the game (GlareSpreadEffect) blurs the frame at the scales sigma_k = SIGMA0_DEG x 2^k; the weights w_k >= 0
(non-negative least squares on the RELATIVE error over a log-spaced theta grid) make  sum_k w_k g_k(theta)  follow f
over FIT_MIN_DEG .. FIT_MAX_DEG, with g_k the normalised 2D Gaussian (per sr, small-angle plane):
g_k(theta) = exp(-theta^2 / (2 sigma_k^2)) / (2 pi sigma_k^2).

    python tools/glare_kernel_fit.py            # prints the fit report, rewrites the generated GDScript file
    python tools/glare_kernel_fit.py --no-write
"""
import math
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import nnls

AGE_YEARS = 25.0  # [call: a young observer] (T10's comparison used 25 as well)
PIGMENTATION = 0.5  # [S: CIE 146:2002, average eye pigmentation]
SIGMA0_DEG = 0.1  # the smallest scale = the lower end of the function's validity
LEVELS = 10  # sigma_9 = 51.2 deg: about the half width of a wide frame
FIT_MIN_DEG = 0.1
FIT_MAX_DEG = 60.0
SAMPLES = 600
OUT = Path(__file__).resolve().parents[1] / "game" / "world" / "glare_spread_kernel.gd"


def cie146(theta_deg, age=AGE_YEARS, p=PIGMENTATION):
    age_term = 1.0 + (age / 62.5) ** 4
    return 10.0 / theta_deg ** 3 + (5.0 / theta_deg ** 2 + 0.1 * p / theta_deg) * age_term + 0.0025 * p


def gaussian(theta_deg, sigma_deg):
    """Normalised 2D Gaussian per steradian (theta, sigma in degrees; small-angle plane)."""
    sigma_rad = math.radians(sigma_deg)
    return np.exp(-(theta_deg / sigma_deg) ** 2 / 2.0) / (2.0 * math.pi * sigma_rad ** 2)


def fit():
    theta = np.geomspace(FIT_MIN_DEG, FIT_MAX_DEG, SAMPLES)
    target = cie146(theta)
    sigmas = [SIGMA0_DEG * 2 ** k for k in range(LEVELS)]
    basis = np.stack([gaussian(theta, s) for s in sigmas], axis=1)
    weights, _ = nnls(basis / target[:, None], np.ones_like(target))  # relative error
    return theta, target, sigmas, weights, basis


def planar_energy(values, theta_deg):
    """Integral of f over the plane annulus [theta_min, theta_max] (sr, planar: 2 pi theta dtheta)."""
    t = np.radians(theta_deg)
    return float(np.trapezoid(values * 2.0 * math.pi * t, t))


def main():
    theta, target, sigmas, weights, basis = fit()
    model = basis @ weights
    rel = model / target - 1.0
    print("sigma_k (deg) / w_k:")
    for s, w in zip(sigmas, weights):
        print("  %8.3f  %.6e" % (s, w))
    print("relative error over %.1f .. %.0f deg: max |e| %.3f at %.2f deg, rms %.3f" % (
        FIT_MIN_DEG, FIT_MAX_DEG, np.abs(rel).max(), theta[np.abs(rel).argmax()], math.sqrt(np.mean(rel ** 2))))
    for t in (0.2, 0.5, 1, 2, 5, 10, 30):
        print("  theta %5.1f deg: CIE %.5g  fit %.5g  error %+.1f %%" % (
            t, cie146(t), sum(w * gaussian(t, s) for w, s in zip(weights, sigmas)),
            100.0 * (sum(w * gaussian(t, s) for w, s in zip(weights, sigmas)) / cie146(t) - 1.0)))
    print("energy (planar) over %.1f .. %.0f deg: CIE %.4f  fit %.4f" % (
        FIT_MIN_DEG, FIT_MAX_DEG, planar_energy(target, theta), planar_energy(model, theta)))
    print("sum of weights (the Gaussians' total energy) %.4f" % weights.sum())
    if "--no-write" in sys.argv:
        return
    lines = [
        "class_name GlareSpreadKernel",
        "extends RefCounted",
        "## GENERATED by tools/glare_kernel_fit.py - do not edit by hand.",
        "## The CIE 146:2002 general disability glare function as a sum of Gaussians (non-negative weights fitted on the",
        "## relative error over %.1f .. %.0f deg, max |error| %.3f, rms %.3f; age %g, p %g)." % (
            FIT_MIN_DEG, FIT_MAX_DEG, np.abs(rel).max(), math.sqrt(np.mean(rel ** 2)), AGE_YEARS, PIGMENTATION),
        "",
        "const AGE_YEARS := %r" % AGE_YEARS,
        "const PIGMENTATION := %r" % PIGMENTATION,
        "const SIGMA0_DEG := %r" % SIGMA0_DEG,
        "const FIT_MIN_DEG := %r" % FIT_MIN_DEG,
        "const FIT_MAX_DEG := %r" % FIT_MAX_DEG,
        "const FIT_MAX_ERROR := %.4f" % np.abs(rel).max(),
        "## Weights w_k (1/sr) of the Gaussians of sigma SIGMA0_DEG x 2^k.",
        "const WEIGHTS := [" + ", ".join("%.8e" % w for w in weights) + "]",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
