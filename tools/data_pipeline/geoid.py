"""EGM2008 geoid undulation (Earth terrain M8, part 1).

Source: the PROJ CDN grid us_nga_egm08_25.tif (NGA EGM2008, 2.5' nodes, public domain; float32 GeoTIFF, node-registered:
pixel centres at -180 + i/24 deg and 90 - j/24 deg, 8640 x 4321 values, no +180 column). The value is the undulation N
of the geoid above the WGS84 ellipsoid (h_ellipsoid = H_geoid + N).

Output:
  data/geoid/egm2008_25.toml + .i16   the fine grid (int16, dn 0.01 m) in the `[grid]` format read by
                                      core/src/config/lunar_site_config.cpp (`load_terrain_grid_file`)
  config/geoid/egm2008_1deg.csv       committed coarse grid (181 x 361, cm), written with `--write-config`

Usage: python tools/data_pipeline/geoid.py [--write-config] [--write-reference]   (after fetch.py geoid_egm2008)
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np

LINES = 4321
SAMPLES = 8640
NODES_PER_DEGREE = 24  # 2.5' = 1/24 deg
DN_SCALE_M = 0.01
NORTH_LATITUDE_DEG = 90.0
WEST_LONGITUDE_DEG = -180.0
STEP_DEG = 1.0 / NODES_PER_DEGREE
SOURCE_FILE = "us_nga_egm08_25.tif"
REPO_ROOT = Path(__file__).resolve().parents[2]

CSV_HEADER = (
    "# EGM2008 geoid undulation N above the WGS84 ellipsoid, 1 degree nodes, in cm (integers).\n"
    "# 181 rows (90 N .. 90 S) x 361 columns (180 W .. 180 E inclusive; column 360 repeats column 0).\n"
    "# Source: NGA EGM2008 2.5' grid via the PROJ CDN file us_nga_egm08_25.tif (NGA, public domain);\n"
    "# the nodes at whole degrees are taken as they are (no averaging).\n"
    "# Generated by: python tools/data_pipeline/geoid.py --write-config\n"
    "# Licence: derived from work by NGA, public domain.\n"
)

# [[check]] points of the fine grid and the reference points file: (name, latitude_deg, longitude_deg)
REFERENCE_POINTS = [
    ("starbase", 25.9972, -97.1561),
    ("lc39a", 28.6082, -80.6041),
    ("slc40", 28.5619, -80.5772),
    ("asds_atlantic_downrange", 31.35, -75.45),
    ("asds_atlantic_bahamas", 28.45, -77.55),
    ("asds_pacific_area", 31.2, -121.3),
    ("pacific_san_diego", 32.60, -117.80),
    ("pacific_open", 10.4, -150.6),
    ("indian_ocean", -30.3, 80.6),
    ("north_atlantic", 45.5, -30.4),
    ("south_pacific", -45.45, -120.35),
    ("antimeridian_east", 0.0, 179.99),
    ("antimeridian_west", 0.0, -179.99),
]
CHECK_POINTS = [(lat, lon) for _, lat, lon in REFERENCE_POINTS]


# ----------------------------------------------------------------------------------------------- pure functions

def to_cm(values_m: np.ndarray) -> np.ndarray:
    return np.rint(values_m * 100.0).astype(np.int32)


def downsample_1deg(cm: np.ndarray) -> np.ndarray:
    """The 2.5' nodes at whole degrees (181 x 361; the +180 column repeats -180)."""
    if cm.shape != (LINES, SAMPLES):
        raise ValueError(f"expected {(LINES, SAMPLES)}, got {cm.shape}")
    coarse = cm[::NODES_PER_DEGREE, ::NODES_PER_DEGREE]
    return np.concatenate([coarse, coarse[:, :1]], axis=1).astype(np.int32)


def write_coarse_csv(path: Path, coarse_cm: np.ndarray) -> None:
    if coarse_cm.shape != (181, 361):
        raise ValueError(f"expected (181, 361), got {coarse_cm.shape}")
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = (",".join(str(int(v)) for v in row) for row in coarse_cm)
    path.write_text(CSV_HEADER + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")


def read_coarse_csv(path: Path) -> np.ndarray:
    rows = [line for line in path.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")]
    return np.array([[int(v) for v in row.split(",")] for row in rows], dtype=np.int32)


def bilinear_m(cm: np.ndarray, lat_deg: float, lon_deg: float) -> float:
    """Bilinear undulation (m) of the 2.5' grid at a position; longitude wraps."""
    line = (NORTH_LATITUDE_DEG - lat_deg) / STEP_DEG
    sample = ((lon_deg - WEST_LONGITUDE_DEG) / STEP_DEG) % SAMPLES
    l0 = min(max(int(math.floor(line)), 0), LINES - 2)
    s0 = int(math.floor(sample))
    fl, fs = line - l0, sample - s0
    s1 = (s0 + 1) % SAMPLES
    v = ((1 - fl) * ((1 - fs) * cm[l0, s0] + fs * cm[l0, s1]) + fl * ((1 - fs) * cm[l0 + 1, s0] + fs * cm[l0 + 1, s1]))
    return float(v) * DN_SCALE_M


def grid_header_text(checks: list[tuple[float, float, float]]) -> str:
    text = ("# EGM2008 geoid undulation, 2.5' nodes - written by tools/data_pipeline/geoid.py\n"
            "[grid]\n"
            'product = "EGM2008_2.5min"\n'
            'projection = "geographic"\n'
            'height_reference = "egm2008_undulation"\n'
            "sphere_radius_m = 6378137.0\n"
            f"dn_scale_m = {DN_SCALE_M}\n"
            'heights = "egm2008_25.i16"\n'
            f"lines = {LINES}\n"
            f"samples = {SAMPLES}\n"
            f"north_latitude_deg = {NORTH_LATITUDE_DEG}\n"
            f"west_longitude_deg = {WEST_LONGITUDE_DEG}\n"
            f"step_latitude_deg = {STEP_DEG!r}\n"
            f"step_longitude_deg = {STEP_DEG!r}\n"
            "global_longitude = true\n")
    for lat, lon, h in checks:
        text += f"\n[[check]]\nlatitude_deg = {lat!r}\nlongitude_deg = {lon!r}\nheight_m = {h!r}\n"
    return text


# ----------------------------------------------------------------------------------------------- files

def read_source_cm(tif: Path) -> np.ndarray:
    import rasterio  # imported here: only the fetch needs it

    with rasterio.open(tif) as ds:
        if ds.shape != (LINES, SAMPLES):
            raise RuntimeError(f"{tif}: shape {ds.shape}, expected {(LINES, SAMPLES)}")
        t = ds.transform
        if (abs(t.a - STEP_DEG) > 1e-12 or abs(t.e + STEP_DEG) > 1e-12
                or abs(t.c - (WEST_LONGITUDE_DEG - STEP_DEG / 2)) > 1e-9
                or abs(t.f - (NORTH_LATITUDE_DEG + STEP_DEG / 2)) > 1e-9):
            raise RuntimeError(f"{tif}: unexpected geotransform {t}")
        values = ds.read(1)
    if not np.isfinite(values).all():
        raise RuntimeError(f"{tif}: non-finite undulation values")
    cm = to_cm(values.astype(np.float64))
    if cm.min() < -32768 or cm.max() > 32767:
        raise RuntimeError("undulation does not fit int16 at 0.01 m")
    return cm


def write_fine_grid(cm: np.ndarray, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "egm2008_25.i16").write_bytes(cm.astype("<i2").tobytes())
    checks = [(lat, lon, bilinear_m(cm, lat, lon)) for lat, lon in CHECK_POINTS]
    (out_dir / "egm2008_25.toml").write_text(grid_header_text(checks), encoding="utf-8")


def load_fine_cm(data_dir: Path) -> np.ndarray:
    return np.fromfile(data_dir / "egm2008_25.i16", dtype="<i2").reshape(LINES, SAMPLES).astype(np.int32)


def write_reference_points(cm: np.ndarray, path: Path) -> None:
    """tests/validation/geoid/egm2008_points.csv: reference points sampled from the 2.5' grid, plus the measured error
    of the committed 1-degree grid (bilinear) at them and over a dense lattice."""
    coarse = downsample_1deg(cm)

    def coarse_m(lat: float, lon: float) -> float:
        line = NORTH_LATITUDE_DEG - lat
        sample = (lon + 180.0) % 360.0
        l0 = min(max(int(math.floor(line)), 0), 179)
        s0 = int(math.floor(sample))
        fl, fs = line - l0, sample - s0
        v = ((1 - fl) * ((1 - fs) * coarse[l0, s0] + fs * coarse[l0, s0 + 1])
             + fl * ((1 - fs) * coarse[l0 + 1, s0] + fs * coarse[l0 + 1, s0 + 1]))
        return float(v) / 100.0

    rng = np.random.default_rng(2008)
    worst = max(abs(coarse_m(lat, lon) - bilinear_m(cm, lat, lon))
                for lat, lon in zip(rng.uniform(-85, 85, 20000), rng.uniform(-180, 180, 20000)))
    at_points = [abs(coarse_m(lat, lon) - bilinear_m(cm, lat, lon)) for _, lat, lon in REFERENCE_POINTS]
    lines = [
        "# EGM2008 undulation N (m above WGS84) reference points for core/tests/test_geoid.cpp.",
        "# Source: the NGA EGM2008 2.5' grid (PROJ CDN us_nga_egm08_25.tif, public domain), bilinear at the point,",
        "# regenerated by: python tools/data_pipeline/geoid.py --write-reference. NGA's online point calculator was not",
        "# reachable from the build machine; the 2.5' grid is NGA's own product (egm08_25.gtx).",
        f"# Measured error of the committed 1-degree grid (bilinear) against the 2.5' grid: max over these points "
        f"{max(at_points):.3f} m; max over 20000 random points between 85 S and 85 N {worst:.3f} m (seed 2008).",
        "name,latitude_deg,longitude_deg,undulation_m",
    ]
    for name, lat, lon in REFERENCE_POINTS:
        lines.append(f"{name},{lat!r},{lon!r},{bilinear_m(cm, lat, lon):.4f}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"  1-degree grid error: points {max(at_points):.3f} m, random {worst:.3f} m")


def fetch(source: dict, repo_root: Path, download, force: bool = False) -> None:
    out_dir = repo_root / "data" / "geoid"
    if (out_dir / "egm2008_25.toml").exists() and not force:
        print("  already present")
        return
    tif = out_dir / SOURCE_FILE
    if force or not tif.exists():
        download(source["url"], tif)
    write_fine_grid(read_source_cm(tif), out_dir)
    print(f"  EGM2008 2.5' grid -> {out_dir / 'egm2008_25.i16'}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-config", action="store_true", help="regenerate config/geoid/egm2008_1deg.csv")
    parser.add_argument("--write-reference", action="store_true", help="regenerate tests/validation/geoid/egm2008_points.csv")
    args = parser.parse_args()
    cm = load_fine_cm(REPO_ROOT / "data" / "geoid")
    if args.write_config:
        write_coarse_csv(REPO_ROOT / "config" / "geoid" / "egm2008_1deg.csv", downsample_1deg(cm))
    if args.write_reference:
        write_reference_points(cm, REPO_ROOT / "tests" / "validation" / "geoid" / "egm2008_points.csv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
