"""Generate core/include/starsim/integrators/dop853_tableau.hpp from SciPy's coefficient table.

Usage: python tools/codegen/gen_dop853_tableau.py <path/to/scipy/integrate/_ivp/dop853_coefficients.py>

Source: SciPy v1.14.1, scipy/integrate/_ivp/dop853_coefficients.py (BSD-3-Clause),
which transcribes Hairer, Norsett & Wanner, "Solving Ordinary Differential Equations I", DOP853.
The file is parsed as text (never executed). Coefficients are copied verbatim as decimal literals.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

N_STAGES = 12
N_EXTENDED = 16
N_DENSE = 4  # INTERPOLATOR_POWER - 3
OUTPUT = Path(__file__).resolve().parents[2] / "core/include/starsim/integrators/dop853_tableau.hpp"


def parse(text: str) -> dict:
    c_block = re.search(r"C = np\.array\(\[(.*?)\]\)", text, re.S).group(1)
    c = [v.strip() for v in c_block.replace("\n", "").split(",") if v.strip()]
    assert len(c) == N_EXTENDED, len(c)

    a = [["0.0"] * N_EXTENDED for _ in range(N_EXTENDED)]
    for i, j, value in re.findall(r"^A\[(\d+), (\d+)\] = (\S+)$", text, re.M):
        a[int(i)][int(j)] = value

    e3_sub = dict(re.findall(r"^E3\[(\d+)\] -= (\S+)$", text, re.M))
    e5 = ["0.0"] * (N_STAGES + 1)
    for i, value in re.findall(r"^E5\[(\d+)\] = (\S+)$", text, re.M):
        e5[int(i)] = value

    d = [["0.0"] * N_EXTENDED for _ in range(N_DENSE)]
    for i, j, value in re.findall(r"^D\[(\d+), (\d+)\] = (\S+)$", text, re.M):
        d[int(i)][int(j)] = value

    b = a[N_STAGES][:N_STAGES]  # B = A[N_STAGES, :N_STAGES]
    # E3[:-1] = B; E3[k] -= x  ->  expressed as "B - x" literal pairs
    e3 = [f"({b[k]}) - ({e3_sub[str(k)]})" if str(k) in e3_sub else b[k] for k in range(N_STAGES)] + ["0.0"]
    return {"c": c, "a": a, "b": b, "e3": e3, "e5": e5, "d": d}


def fmt_row(values: list[str]) -> str:
    return "{" + ", ".join(values) + "}"


def render(t: dict) -> str:
    a_rows = ",\n        ".join(fmt_row(r) for r in t["a"])
    d_rows = ",\n        ".join(fmt_row(r) for r in t["d"])
    return f"""#pragma once

// GENERATED by tools/codegen/gen_dop853_tableau.py - do not edit by hand.
// Dormand-Prince 8(5,3) "DOP853" Butcher tableau incl. dense-output coefficients.
// Source: SciPy v1.14.1 scipy/integrate/_ivp/dop853_coefficients.py (BSD-3-Clause),
// after Hairer, Norsett & Wanner, Solving Ordinary Differential Equations I.

#include <array>

namespace starsim::integrators::dop853 {{

inline constexpr int n_stages = {N_STAGES};
inline constexpr int n_stages_extended = {N_EXTENDED};
inline constexpr int n_dense = {N_DENSE};

inline constexpr std::array<double, {N_EXTENDED}> c = {fmt_row(t["c"])};

inline constexpr std::array<std::array<double, {N_EXTENDED}>, {N_EXTENDED}> a = {{{{
        {a_rows}
}}}};

inline constexpr std::array<double, {N_STAGES}> b = {fmt_row(t["b"])};

inline constexpr std::array<double, {N_STAGES + 1}> e3 = {fmt_row(t["e3"])};

inline constexpr std::array<double, {N_STAGES + 1}> e5 = {fmt_row(t["e5"])};

inline constexpr std::array<std::array<double, {N_EXTENDED}>, {N_DENSE}> d = {{{{
        {d_rows}
}}}};

}}  // namespace starsim::integrators::dop853
"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 1
    tableau = parse(Path(sys.argv[1]).read_text())
    OUTPUT.write_text(render(tableau))
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
